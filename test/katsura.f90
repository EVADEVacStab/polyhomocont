  subroutine build_katsura(n, sys)
    !! Katsura-n in the unknowns u_0, ..., u_n (stored as variables
    !! 1, ..., n + 1):
    !!   u_0 + 2 (u_1 + ... + u_n) - 1 = 0,
    !!   sum_{l=-n}^{n} u_{|l|} u_{|m-l|} - u_m = 0,  m = 0, ..., n - 1,
    !! with u_k = 0 for k > n. Repeated monomials are passed as separate
    !! terms.

    integer, intent(in) :: n
    type(sparse_system), intent(out) :: sys

    real(wp), allocatable :: coefs(:)
    integer, allocatable :: exps(:, :)
    integer :: e(n + 1)
    integer :: status
    integer :: m
    integer :: l
    integer :: k

    call sys%init(n + 1)

    ! Linear equation
    allocate(coefs(n + 2))
    allocate(exps(n + 1, n + 2))
    exps = 0
    coefs(1) = 1.0_wp
    exps(1, 1) = 1
    do k = 1, n
      coefs(k + 1) = 2.0_wp
      exps(k + 1, k + 1) = 1
    end do
    coefs(n + 2) = -1.0_wp
    call sys%add_equation(coefs, exps, status)
    call assert_status("katsura: linear equation", status)

    ! Quadratic equations
    do m = 0, n - 1
      deallocate(coefs)
      deallocate(exps)
      allocate(coefs(0))
      allocate(exps(n + 1, 0))
      do l = -n, n
        if (abs(m - l) > n) cycle
        e = 0
        e(abs(l) + 1) = e(abs(l) + 1) + 1
        e(abs(m - l) + 1) = e(abs(m - l) + 1) + 1
        coefs = [coefs, 1.0_wp]
        exps = reshape([exps, e], [n + 1, size(coefs)])
      end do
      e = 0
      e(m + 1) = 1
      coefs = [coefs, -1.0_wp]
      exps = reshape([exps, e], [n + 1, size(coefs)])
      call sys%add_equation(coefs, exps, status)
      call assert_status("katsura: quadratic equation", status)
    end do

  end subroutine build_katsura

  subroutine check_katsura(n, sols, nreal)

    integer, intent(in) :: n
    complex(wp), intent(in) :: sols(:, :)
    integer, intent(in) :: nreal

    type(sparse_system) :: sys
    type(solve_result) :: res
    character(len=12) :: name
    integer :: status
    integer :: k

    write(name, "(a,i0)") "katsura-", n
    call build_katsura(n, sys)
    call solve(sys, res, status)
    call assert_status(trim(name)//": solve", status)
    call assert_equal(trim(name)//": paths", res%npaths, 2**n)
    call assert_equal(trim(name)//": solutions", res%nsolutions, 2**n)
    call assert_equal(trim(name)//": real solutions", res%nreal, nreal)
    call assert_equal(trim(name)//": failed paths", res%nfailed, 0)
    call assert_equal(trim(name)//": duplicates", res%nduplicates, 0)
    call assert_small(trim(name)//": distance to reference",  &
      set_distance(res%solutions, sols), 1.0e-12_wp)
    call assert_small(trim(name)//": max residual",  &
      maxval([(res%paths(k)%residual, k = 1, res%npaths)]), 1.0e-14_wp)

  end subroutine check_katsura

